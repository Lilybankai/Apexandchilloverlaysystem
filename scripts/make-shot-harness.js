/**
 * scripts/make-shot-harness.js — the stubbed-bridge screenshot harness.
 * -----------------------------------------------------------------------------
 * The control panel only runs inside Electron: the renderer talks to
 * `window.apex`, which exists because preload.js built it. That makes "what
 * does the Settings screen look like now?" surprisingly hard to answer without
 * launching the whole app signed-in — and the APEX_SHOT hook can only capture
 * the page the app opens on.
 *
 * This generates a copy of index.html that runs in a PLAIN browser:
 *
 *   node scripts/make-shot-harness.js
 *   node scripts/serve-panel.js          # (or any static server on the dir)
 *   msedge --headless --screenshot=out.png \
 *     "http://127.0.0.1:17555/__shot-harness.html?tab=schedule"
 *
 * Three things it deals with, each learned the slow way:
 *   - The page's CSP is `script-src 'self'` — an INLINE stub script is
 *     silently ignored, so the stub goes in an external __shot-stub.js.
 *   - localStorage is unavailable on file:// — the harness must be served
 *     over http for the seeded tab/pane keys to be readable.
 *   - Clicking through to a view races the renderer's async init — so the
 *     stub does not click anything; it seeds `apex.panel.tab` = settings
 *     (and the pane from ?pane=) BEFORE control-panel.js reads them.
 *
 * The generated files are gitignored and excluded from packaging: they are a
 * dev tool, and a stale snapshot of index.html must never ship.
 */

